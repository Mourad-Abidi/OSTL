# neural.py
"""Amortized program oracle — a real PyTorch network that predicts
which DSL program generated a given (input, output) example.

Trained on synthetic data generated by running every small DSL program
on sampled inputs. Used as a fast proposal engine at teach time; the
symbolic search still runs to *verify* and (if no neural proposal fits)
to solve from scratch.
"""
import math, random
from dsl import Type, type_of, all_primitives
from program import Constant, Variable, PrimitiveNode
from itertools import product
from collections import defaultdict

try:
    import torch
    import torch.nn as nn
    import torch.nn.functional as F
    HAS_TORCH = True
except ImportError:
    HAS_TORCH = False

FEAT = 20  # features per value


# ── encoding ────────────────────────────────────────────────
def encode_value(v):
    f = [0.0] * FEAT
    if isinstance(v, bool):
        f[0] = 1.0; f[1] = float(v)
    elif isinstance(v, (int, float)):
        f[2]  = 1.0
        f[3]  = math.tanh(float(v) / 20)
        f[4]  = 1.0 if v > 0 else (-1.0 if v < 0 else 0.0)
        f[5]  = abs(float(v)) % 2
        f[6]  = abs(float(v)) % 3
        f[7]  = abs(float(v)) % 4
        f[8]  = abs(float(v)) % 5
        f[9]  = math.log(abs(float(v)) + 1) / 5
    elif isinstance(v, str):
        n = max(len(v), 1)
        f[10] = 1.0
        f[11] = min(len(v), 15) / 15
        f[12] = sum(c.isupper() for c in v) / n
        f[13] = sum(c.islower() for c in v) / n
        f[14] = sum(c.isdigit() for c in v) / n
        f[15] = 1.0 if v and v == v[::-1] else 0.0
        f[16] = (hash(v) % 1000) / 1000
        if v:
            f[17] = ord(v[0]) / 128
            f[18] = ord(v[-1]) / 128
    else:
        f[19] = 1.0
    return f


def encode_example(inp, out):
    return encode_value(inp) + encode_value(out)  # FEAT*2 dims


# ── program enumeration ─────────────────────────────────────
def _splits(total, parts):
    if parts == 1: return [(total,)]
    out = []
    for i in range(1, total - parts + 2):
        for rest in _splits(total - i, parts - 1):
            out.append((i,) + rest)
    return out


def enumerate_programs(max_size=2):
    programs = defaultdict(list)
    for c in [0, 1, 2, 3, 10, True, False, "", "a"]:
        programs[1].append(Constant(c))
    programs[1].append(Variable(0))

    for size in range(2, max_size + 1):
        for prim in all_primitives():
            if size - 1 < prim.arity:
                continue
            for split in _splits(size - 1, prim.arity):
                if any(not programs[s] for s in split):
                    continue
                sub_lists = [programs[s] for s in split]
                for args in product(*sub_lists):
                    programs[size].append(PrimitiveNode(prim, list(args)))

    return [p for s in range(1, max_size + 1) for p in programs[s]]


# ── training data ───────────────────────────────────────────
_INPUT_POOL = {
    Type.NUM:  [-5, -3, -1, 0, 1, 2, 3, 5, 7, 10],
    Type.STR:  ["a", "ab", "abc", "hi", "hello", "xyz", "WORLD"],
    Type.BOOL: [True, False],
}


def _sample_inputs(prog, n=20):
    """Try each type until the program produces non-None outputs."""
    for t in (Type.NUM, Type.STR, Type.BOOL):
        pool = _INPUT_POOL[t]
        try:
            samples = [random.choice(pool) for _ in range(n)]
            results = [prog.eval([s]) for s in samples]
            if all(r is not None for r in results):
                return samples, results
        except Exception:
            continue
    return None, None


def generate_training_data(max_size=2, samples_per_program=20):
    candidates = enumerate_programs(max_size)
    programs, X, y = [], [], []
    for prog in candidates:
        if len(prog.variables()) != 1:
            continue
        samples, results = _sample_inputs(prog, samples_per_program)
        if samples is None:
            continue
        idx = len(programs)
        programs.append(prog)
        for s, r in zip(samples, results):
            X.append(encode_example(s, r))
            y.append(idx)
    return programs, X, y


# ── model ───────────────────────────────────────────────────
if HAS_TORCH:
    class ProgramClassifier(nn.Module):
        def __init__(self, num_programs, hidden=128):
            super().__init__()
            self.net = nn.Sequential(
                nn.Linear(FEAT * 2, hidden), nn.ReLU(),
                nn.Linear(hidden, hidden),  nn.ReLU(),
                nn.Linear(hidden, num_programs),
            )
        def forward(self, x):
            return self.net(x)


# ── training ────────────────────────────────────────────────
def train_oracle(max_size=2, samples_per_program=20, epochs=25, hidden=128):
    if not HAS_TORCH:
        print("PyTorch not installed — neural oracle disabled.")
        return None
    programs, X, y = generate_training_data(max_size, samples_per_program)
    if not programs:
        print("No valid training programs found.")
        return None
    print(f"Neural oracle: {len(programs)} programs, {len(X)} examples")

    model = ProgramClassifier(len(programs), hidden)
    Xt = torch.tensor(X, dtype=torch.float32)
    yt = torch.tensor(y, dtype=torch.long)
    dl = torch.utils.data.DataLoader(
        torch.utils.data.TensorDataset(Xt, yt), batch_size=128, shuffle=True)
    opt = torch.optim.Adam(model.parameters(), lr=1e-3)

    for epoch in range(epochs):
        model.train()
        total, correct = 0.0, 0
        for bx, by in dl:
            opt.zero_grad()
            logits = model(bx)
            loss = F.cross_entropy(logits, by)
            loss.backward(); opt.step()
            total += loss.item() * bx.size(0)
            correct += (logits.argmax(dim=1) == by).sum().item()
        if (epoch + 1) % 5 == 0 or epoch == epochs - 1:
            print(f"  epoch {epoch+1:>2}/{epochs}  "
                  f"loss={total/len(Xt):.3f}  acc={correct/len(Xt):.2%}")
    model.eval()
    return NeuralOracle(model, programs)


# ── oracle ──────────────────────────────────────────────────
class NeuralOracle:
    def __init__(self, model, programs):
        self.model = model
        self.programs = programs
        self._index = {str(p): i for i, p in enumerate(programs)}

    def propose(self, inp, out, top_k=5):
        if not HAS_TORCH:
            return []
        x = torch.tensor([encode_example(inp, out)], dtype=torch.float32)
        with torch.no_grad():
            probs = F.softmax(self.model(x)[0], dim=0)
            k = min(top_k, len(self.programs))
            top = torch.topk(probs, k)
        return [(self.programs[i], probs[i].item()) for i in top.indices.tolist()]

    def online_update(self, inp, out, program, steps=3, lr=1e-4):
        """One-example gradient step: the net gets smarter after each teach."""
        if not HAS_TORCH:
            return
        key = str(program)
        if key not in self._index:
            return  # program not in vocabulary — can't update
        idx = self._index[key]
        x = torch.tensor([encode_example(inp, out)], dtype=torch.float32)
        y = torch.tensor([idx], dtype=torch.long)
        opt = torch.optim.SGD(self.model.parameters(), lr=lr)
        self.model.train()
        for _ in range(steps):
            opt.zero_grad()
            F.cross_entropy(self.model(x), y).backward()
            opt.step()
        self.model.eval()

    def save(self, path):
        if not HAS_TORCH: return
        torch.save({
            "state": self.model.state_dict(),
            "programs": [p.to_dict() for p in self.programs],
        }, path)

    @classmethod
    def load(cls, path):
        if not HAS_TORCH: return None
        from program import program_from_dict
        data = torch.load(path, weights_only=False)
        programs = [program_from_dict(d) for d in data["programs"]]
        model = ProgramClassifier(len(programs))
        model.load_state_dict(data["state"])
        model.eval()
        return cls(model, programs)